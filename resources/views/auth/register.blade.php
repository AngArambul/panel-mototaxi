<script>
        document.addEventListener('DOMContentLoaded', function() {
            // 1. Obtener referencias a los elementos del formulario
            const registerForm = document.querySelector('form');
            const submitButton = registerForm.querySelector('button[type="submit"]');
            const passwordInput = document.getElementById('password');
            const confirmPasswordInput = document.getElementById('password_confirmation');

            registerForm.addEventListener('submit', function(event) {
                // 1. Validar que las contraseñas coincidan
                if (passwordInput.value !== confirmPasswordInput.value) {
                    event.preventDefault(); // Detiene el envío del formulario
                    alert('Las contraseñas no coinciden. Por favor, escríbelas igual.');
                    passwordInput.focus();
                    return false;
                }
                // 2. Deshabilita el botón de envío y cambiar su texto
                submitButton.disabled = true;
                submitButton.style.opacity = '0.7';
                submitButton.innerText = 'Registrando usuario...';
            });
        });
    </script>